import { unsplashPhoto } from '../utils/images'

const L = (ar: string, en: string): LocalizedText => ({ ar, en })

function photo(id: string): string {
  return unsplashPhoto(id, { width: 1000, height: 1200 })
}

function createProduct(
  product: Omit<Product, 'images' | 'featured' | 'isNew' | 'isBestSeller' | 'stock'> &
    Partial<Pick<Product, 'images' | 'featured' | 'isNew' | 'isBestSeller' | 'stock'>>,
): Product {
  const images = product.images && product.images.length > 0 ? product.images : [product.image]
  const discount =
    product.discount ??
    (product.oldPrice && product.oldPrice > product.price
      ? Math.round(((product.oldPrice - product.price) / product.oldPrice) * 100)
      : undefined)

  return {
    featured: false,
    isNew: false,
    isBestSeller: false,
    stock: 18,
    ...product,
    images,
    discount,
  }
}

function specs(...entries: Array<[string, string, string, string]>): ProductSpec[] {
  return entries.map(([arLabel, enLabel, arValue, enValue]) => ({
    label: L(arLabel, enLabel),
    value: L(arValue, enValue),
  }))
}

